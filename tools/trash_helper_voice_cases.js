window.vaRun = function () {
  const out = [], bad = [];
  for (const [q, exp] of window.VA_CORPUS) {
    const u = TH.assistant.understand(q), p = TH.assistant.decide(u);
    const got = (p.kind === "plan" ? `plan:${p.items.join(",")}` : p.kind === "map" ? `map:${p.layer}` : p.kind) + (p.check ? `?${p.check}` : "");
    const sorted = x => x.replace(/^plan:([^?]*)/, (_, ids) => "plan:" + ids.split(",").sort().join());
    const ok = sorted(got) === sorted(exp);
    if (!ok) bad.push(`${q} → ${got}  (want ${exp})`);
  }
  return `${window.VA_CORPUS.length - bad.length}/${window.VA_CORPUS.length} ok\n` + bad.join("\n");
};
