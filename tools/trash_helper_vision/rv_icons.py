"""Tabler icons used by 回收小里長's items / steps / places, for the scan result card (sort.js).

    python3 tools/trash_helper_vision/rv_icons.py

Reads @tabler/icons (MIT) from the recycle-li build (build/recycle-vision, see build.sh) and the item list
(vendor/recycle-vision/data/rv_items.json); writes microservices/trash_helper/vendor/tabler/rv-icons.js, which adds
the icons missing from vendor/tabler/icons.js to window.TH_ICONS.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLER = ROOT / "build/recycle-vision/recycle-li/web/node_modules/@tabler/icons"
SVC = ROOT / "microservices/trash_helper"
kebab = lambda s: re.sub(r"(?<=[a-z0-9])(?=[A-Z0-9])", "-", s).lower()

items = json.loads((SVC / "vendor/recycle-vision/data/rv_items.json").read_text())
names = {kebab(i["icon"]) for i in items}
names |= {"glass-off", "droplets", "arrows-minimize", "scissors", "package", "bandage", "tag", "droplet-half-2", "wind",  # steps
          "truck", "bucket", "recycle", "building-store", "phone", "building-hospital",                               # places
          "category", "calendar", "map-pin", "bulb", "hand-stop", "camera", "home", "trash", "leaf", "file-text", "bottle",
          "cylinder", "milk", "battery-2", "sofa", "alert-triangle", "news"}
have = set(re.findall(r'"([a-z0-9-]+)":\[\[', (SVC / "vendor/tabler/icons.js").read_text()))
nodes = json.loads((TABLER / "tabler-nodes-outline.json").read_text())
version = json.loads((TABLER / "package.json").read_text())["version"]
add = {n: nodes[n] for n in sorted(names - have) if n in nodes}
missing = sorted(n for n in names - have if n not in nodes)
out = SVC / "vendor/tabler/rv-icons.js"
out.write_text(f"// Tabler Icons {version} (MIT, https://tabler.io/icons) — icons for 回收小里長 items, generated by tools/trash_helper_vision/rv_icons.py\n"
               f"Object.assign(window.TH_ICONS, {json.dumps(add, separators=(',', ':'))});\n")
print(f"{len(add)} icons → {out.relative_to(ROOT)}", "missing:", missing)
