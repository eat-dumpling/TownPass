"""Build microservices/trash_helper/i18n/<code>.js from translator JSON.

Input folder (one set per language):
  <code>.ui.json       {uiKey: text}            UI strings (export the source with
                                                tools/trash_helper_i18n_export.js)
  <code>.ui2.json …    {uiKey: text}            later additions (merged in name order)
  <code>.content.json  {englishText: text}      rules.json / rv_map.json content, keyed by English
  <code>.voice.json    {"items": {id: [..]}, "intents": {id: [..]}}   voice-assistant keywords
  <code>.rv.json       {"names": {id: ..}, "notes": {id: ..}}   photo-recognition item names/notes
For "en" only the .rv.json part is built (English UI strings live in the page itself).

Checks every placeholder ({name}) against the English source and refuses mismatches.
Usage: python3 tools/trash_helper_i18n_build.py <folder> <source_ui.json> [code ...]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'microservices/trash_helper/i18n'
PH = re.compile(r'\{(\w+)\}')


def load(p: Path):
    return json.loads(p.read_text(encoding='utf-8')) if p.exists() else {}


def build(folder: Path, src: dict, code: str) -> None:
    ui = {}
    for part in sorted(folder.glob(f'{code}.ui*.json')):   # .ui.json, then later batches .ui2.json, .ui3.json…
        ui.update(load(part))
    content = load(folder / f'{code}.content.json')
    voice = load(folder / f'{code}.voice.json') or {'items': {}, 'intents': {}}
    rv = load(folder / f'{code}.rv.json') or {'names': {}, 'notes': {}}
    dump = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))  # noqa: E731
    if code == 'en':
        OUT.mkdir(exist_ok=True)
        (OUT / 'en.js').write_text('// SPDX-License-Identifier: AGPL-3.0-or-later\n'
                                   '// en: photo-recognition notes in English, generated by tools/trash_helper_i18n_build.py.\n'
                                   '"use strict";\n' f'window.TH_RVTXT.en = {dump(rv)};\n', encoding='utf-8')
        print(f'en: {len(rv.get("notes", {}))} notes')
        return
    problems, missing = [], []
    for key, s in src.items():
        if key not in ui:
            missing.append(key)
            continue
        en, tr = s['en'], ui[key]
        if isinstance(en, list):
            if not (isinstance(tr, list) and len(tr) == len(en)):
                problems.append(f'{key}: needs {len(en)} entries')
        elif sorted(PH.findall(en)) != sorted(PH.findall(str(tr))):
            problems.append(f'{key}: placeholders {PH.findall(en)} vs {PH.findall(str(tr))}')
    for en, tr in content.items():
        if sorted(PH.findall(en)) != sorted(PH.findall(tr)):
            problems.append(f'content "{en[:40]}": placeholders differ')
    if problems:
        raise SystemExit(f'{code}: ' + '; '.join(problems[:10]))
    ui = {k: v for k, v in ui.items() if k in src}
    OUT.mkdir(exist_ok=True)
    js = ('// SPDX-License-Identifier: AGPL-3.0-or-later\n'
          f'// {code}: generated by tools/trash_helper_i18n_build.py. Machine-assisted translation; '
          'missing strings fall back to English.\n'
          '"use strict";\n'
          f'window.TH_STRINGS[{dump(code)}] = {dump(ui)};\n'
          f'window.TH_CONTENT[{dump(code)}] = {dump(content)};\n'
          f'window.TH_VOICE[{dump(code)}] = {dump(voice)};\n'
          f'window.TH_RVTXT[{dump(code)}] = {dump(rv)};\n'
          f'(window.TH_LANGS.find(l => l.code === {dump(code)}) || {{}}).ready = true;\n')
    (OUT / f'{code}.js').write_text(js, encoding='utf-8')
    print(f'{code}: {len(ui)}/{len(src)} UI strings, {len(content)} content, '
          f'{len(voice.get("items", {}))} item keyword sets'
          + f', {len(rv.get("names", {}))} item names, {len(rv.get("notes", {}))} notes'
          + (f' — falls back to English for {len(missing)} keys: {", ".join(missing[:8])}' if missing else ''))


def main() -> None:
    folder, src_path, *codes = sys.argv[1:]
    src = json.loads(Path(src_path).read_text(encoding='utf-8'))
    for code in codes or sorted({p.name.split('.')[0] for p in Path(folder).glob('*.ui.json')}):
        build(Path(folder), src, code)


if __name__ == '__main__':
    main()
