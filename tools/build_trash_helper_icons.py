#!/usr/bin/env python3
"""Bundle the Tabler Icons (MIT) that Trash Helper uses into one small script.

Writes microservices/trash_helper/vendor/tabler/icons.js (window.TH_ICONS = {name: nodes})
and the Tabler licence next to it. Only the icons listed in ICONS plus every `icon`
field in data/rules.json are included.

    python3 tools/build_trash_helper_icons.py

SPDX-License-Identifier: AGPL-3.0-or-later
"""
import json
import urllib.request
from pathlib import Path

VERSION = '3.31.0'
BASE = f'https://unpkg.com/@tabler/icons@{VERSION}'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'microservices/trash_helper/vendor/tabler'
RULES = ROOT / 'microservices/trash_helper/data/rules.json'

# Interface icons (the item and step icons come from rules.json).
ICONS = '''direction-sign home camera map file-text shopping-bag help-circle star bell navigation x check chevron-right chevron-left
chevron-down photo phone player-play truck recycle lock clock trash leaf alert-triangle alert-circle walk list search
map-pin building-community building-store calendar-event info-circle external-link layout-grid user-check circle-check
current-location route sparkles home-2 refresh plus music sofa language microphone microphone-off player-stop send volume message-circle pencil columns-2 maximize'''.split()


def fetch(path: str) -> bytes:
    with urllib.request.urlopen(f'{BASE}/{path}', timeout=60) as r:
        return r.read()


def main() -> None:
    nodes = json.loads(fetch('tabler-nodes-outline.json'))
    rules = json.loads(RULES.read_text(encoding='utf-8'))
    names = set(ICONS)
    for it in rules['items']:
        names.add(it['icon'])
        names.update(s['icon'] for s in it['steps'])
    names.update(s['icon'] for s in rules['guide'])
    missing = sorted(n for n in names if n not in nodes)
    if missing:
        raise SystemExit(f'Unknown Tabler icons: {missing}')
    OUT.mkdir(parents=True, exist_ok=True)
    data = {n: nodes[n] for n in sorted(names)}
    (OUT / 'icons.js').write_text(
        f'// Tabler Icons {VERSION} (MIT, https://tabler.io/icons) — subset generated by tools/build_trash_helper_icons.py\n'
        f'window.TH_ICONS = {json.dumps(data, separators=(",", ":"))};\n', encoding='utf-8')
    (OUT / 'LICENSE').write_bytes(fetch('LICENSE'))
    print(f'{len(data)} icons -> {OUT / "icons.js"}')


if __name__ == '__main__':
    main()
