// 在 y=常數 的牆面（左前方那面）上畫一塊方形（窗、門、招牌）
const onY = (y: number, x0: number, x1: number, z0: number, z1: number, c: string): Part => quad([x0, y, z0], [x1, y, z0], [x1, y, z1], [x0, y, z1], c)
// 在 x=常數 的牆面（右前方那面）上畫一塊方形
const onX = (x: number, y0: number, y1: number, z0: number, z1: number, c: string): Part => quad([x, y0, z0], [x, y1, z0], [x, y1, z1], [x, y0, z1], c)

