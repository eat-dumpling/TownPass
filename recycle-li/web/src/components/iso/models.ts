function windmill(): Part[] {
  const blade = (a: number): Part => {
    const c = Math.cos(a), s = Math.sin(a)
    const p = (r: number, w: number): P3 => [0.5 + r * c - w * s, 0.74, 1.0 + r * s + w * c]
    return quad(p(0.05, -0.03), p(0.05, 0.03), p(0.44, 0.07), p(0.44, -0.02), '#FFFFFF', { type: 'l', x1: 0, y1: 0, x2: 1, y2: 1, stops: ['#FFFFFF', '#E3E7E9'] })
  }
  return [
    shadow(0.5, 0.5, 0.45),
    ...box(0.26, 0.28, 0, 0.48, 0.46, 0.12, '#ADB8BE'),
    // 塔身：往上收的四角錐台
    quad([0.3, 0.72, 0.12], [0.7, 0.72, 0.12], [0.62, 0.64, 0.95], [0.38, 0.64, 0.95], '#E9E1D3', { type: 'l', x1: 0, y1: 0, x2: 0, y2: 1, stops: ['#F7F2E7', '#D8CCB6'] }),
    quad([0.7, 0.32, 0.12], [0.7, 0.72, 0.12], [0.62, 0.64, 0.95], [0.62, 0.4, 0.95], '#BFB29B'),
    onY(0.7, 0.44, 0.56, 0.12, 0.34, '#8C5A2E'),
    ...box(0.36, 0.38, 0.95, 0.28, 0.3, 0.16, '#C2332F'),
    ...roof(0.36, 0.38, 1.11, 0.28, 0.3, 0.12, '#8F1D1A', 0.03),
    blade(0.3), blade(0.3 + Math.PI / 2), blade(0.3 + Math.PI), blade(0.3 + (3 * Math.PI) / 2),
    ring(0.5, 0.745, 1.0, 0.04, 'y', '#5E6D76', 1, '#5E6D76'),
  ]
}

